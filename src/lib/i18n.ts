export function t(lang: Lang, key: I18nKey, vars?: Record<string, string>): string {
  let str: string = dict[lang][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, v);
    }
  }
  return str;
}
